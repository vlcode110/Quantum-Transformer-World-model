"""The quantum system being modelled: a driven transverse-field Ising chain.

    H(t) = -J sum_i Z_i Z_{i+1}  -  h(t) sum_i X_i

A chain of N spins. Neighbours want to align (the J term). A control field the
experimenter sets tries to flip them (the h term). The competition between the
two is what makes this the standard minimal model of an interacting quantum
system, and at h = J it sits at a critical point where the dynamics are richest.

Implementation notes
--------------------
The simulation is exact, not Trotterised: the Hamiltonian is built densely and
exponentiated once per field level, then trajectories are generated by
matrix-vector products. At ten spins the state is 1024 complex numbers and a
matrix exponential takes a fraction of a second, so exactness costs nothing and
removes Trotter error as a confound.

Expectation values of Z are computed from the probability distribution directly
rather than by matrix multiplication, because Z_i is diagonal in the
computational basis. That keeps trajectory generation fast even at ten spins.

No shot noise is simulated. Every expectation value here is exact. On real
hardware each would be estimated from finite measurements, which is a separate
question addressed by the shot-noise probe in the Phase 0 directory.
"""
import numpy as np
from scipy.linalg import expm


# ------------------------------------------------------------------ operators
def _pauli_z_signs(n_spins):
    """For each spin, the eigenvalue of Z_i on every basis state.

    Z_i is diagonal: on basis state b, it returns +1 if spin i is up and -1 if
    down. Precomputing these sign vectors turns every later expectation value
    into a dot product with the probability distribution.
    """
    dim = 2 ** n_spins
    idx = np.arange(dim)
    # bit i of the index encodes spin i (spin 0 = most significant bit)
    return np.stack([1.0 - 2.0 * ((idx >> (n_spins - 1 - i)) & 1)
                     for i in range(n_spins)])            # (n_spins, dim)


def _single_site(op, site, n_spins):
    """Embed a 2x2 operator acting on one spin into the full 2^N space."""
    mats = [np.eye(2, dtype=complex)] * n_spins
    mats[site] = op
    out = mats[0]
    for m in mats[1:]:
        out = np.kron(out, m)
    return out


def _two_site(op_a, op_b, i, j, n_spins):
    mats = [np.eye(2, dtype=complex)] * n_spins
    mats[i], mats[j] = op_a, op_b
    out = mats[0]
    for m in mats[1:]:
        out = np.kron(out, m)
    return out


X = np.array([[0, 1], [1, 0]], dtype=complex)
Z = np.array([[1, 0], [0, -1]], dtype=complex)


def hamiltonian(n_spins, coupling, field):
    """Dense H for the transverse-field Ising chain with open boundaries."""
    dim = 2 ** n_spins
    H = np.zeros((dim, dim), dtype=complex)
    for i in range(n_spins - 1):
        H -= coupling * _two_site(Z, Z, i, i + 1, n_spins)
    for i in range(n_spins):
        H -= field * _single_site(X, i, n_spins)
    return H


def evolution_operators(cfg):
    """One time-evolution operator per control-field level, computed once.

    Because the field is piecewise constant, the entire simulation reduces to
    repeatedly applying one of a handful of precomputed matrices."""
    return [expm(-1j * hamiltonian(cfg.n_spins, cfg.coupling, h) * cfg.dt)
            for h in cfg.field_levels]


# --------------------------------------------------------------- measurement
def measure(psi, z_signs, n_spins, observables):
    """Expectation values of the recorded observables for a state.

    <Z_i> comes straight from the probability distribution. <X_i> requires a
    basis rotation, done here by applying X and taking the overlap.
    """
    probs = np.abs(psi) ** 2
    z = z_signs @ probs                                   # (n_spins,)
    if observables == "z":
        return z
    x = np.empty(n_spins)
    for i in range(n_spins):
        x[i] = np.real(np.vdot(psi, _single_site(X, i, n_spins) @ psi))
    return np.concatenate([z, x])


def initial_state(cfg, rng):
    """Starting configuration of the chain.

    'neel' alternates up and down, which is far from the ground state and
    therefore produces rich dynamics rather than a state that barely moves.
    """
    n = cfg.n_spins
    if cfg.init_state == "all_up":
        bits = [0] * n
    elif cfg.init_state == "neel":
        bits = [i % 2 for i in range(n)]
    elif cfg.init_state == "random_product":
        bits = list(rng.integers(0, 2, n))
    else:
        raise ValueError(f"unknown init_state {cfg.init_state!r}")
    idx = 0
    for b in bits:
        idx = (idx << 1) | int(b)
    psi = np.zeros(2 ** n, dtype=complex)
    psi[idx] = 1.0
    return psi


# ------------------------------------------------------------- trajectories
def control_sequence(cfg, rng):
    """The field levels applied along one trajectory.

    'piecewise' holds a level for several steps before switching, producing
    structured dynamics. 'random' switches every step, which is closer to noise
    and gives the model less to learn.
    """
    n_levels = len(cfg.field_levels)
    if cfg.control_mode == "random":
        return rng.integers(0, n_levels, cfg.traj_length)
    seq = np.empty(cfg.traj_length, dtype=np.int64)
    t = 0
    while t < cfg.traj_length:
        level = rng.integers(0, n_levels)
        k = min(cfg.hold_steps, cfg.traj_length - t)
        seq[t:t + k] = level
        t += k
    return seq


def generate(cfg, verbose=True):
    """Produce the full dataset of trajectories.

    Returns observations (n_traj, T, obs_dim), one-hot controls
    (n_traj, T, n_levels), and the integer control indices.
    """
    rng = np.random.default_rng(cfg.seed)
    U = evolution_operators(cfg)
    z_signs = _pauli_z_signs(cfg.n_spins)
    n_levels = len(cfg.field_levels)
    obs_dim = cfg.obs_dim()

    obs = np.empty((cfg.n_trajectories, cfg.traj_length, obs_dim), np.float32)
    act = np.zeros((cfg.n_trajectories, cfg.traj_length, n_levels), np.float32)
    lvl = np.empty((cfg.n_trajectories, cfg.traj_length), np.int64)

    for traj in range(cfg.n_trajectories):
        psi = initial_state(cfg, rng)
        seq = control_sequence(cfg, rng)
        for t in range(cfg.traj_length):
            level = int(seq[t])
            psi = U[level] @ psi
            # renormalise against accumulated floating-point drift
            psi /= np.linalg.norm(psi)
            obs[traj, t] = measure(psi, z_signs, cfg.n_spins, cfg.observables)
            act[traj, t, level] = 1.0
            lvl[traj, t] = level
        if verbose and (traj + 1) % 50 == 0:
            print(f"  trajectory {traj + 1}/{cfg.n_trajectories}")
    return obs, act, lvl


def describe(cfg):
    return (f"{cfg.n_spins}-spin transverse-field Ising chain, J={cfg.coupling}, "
            f"field levels {list(cfg.field_levels)}, dt={cfg.dt}, "
            f"observing {'<Z> only (non-Markovian)' if cfg.observables == 'z' else '<Z> and <X>'}")


def diagnostics(obs, cfg):
    """Sanity checks on the generated data, printed at generation time.

    A dataset where the observables barely move, or where they saturate at the
    edges of their range, cannot support a meaningful prediction task — and
    that failure is silent unless checked.
    """
    flat = obs.reshape(-1, obs.shape[-1])
    step = np.diff(obs, axis=1).reshape(-1, obs.shape[-1])
    return {
        "obs_dim": int(obs.shape[-1]),
        "obs_mean": float(flat.mean()),
        "obs_std": float(flat.std()),
        "obs_min": float(flat.min()),
        "obs_max": float(flat.max()),
        "mean_abs_step": float(np.abs(step).mean()),
        "persistence_mse": float((step ** 2).mean()),
        "variance": float(flat.var(axis=0).mean()),
    }


if __name__ == "__main__":
    from config import Config
    cfg = Config.from_cli()
    print(describe(cfg), "\n")
    obs, act, lvl = generate(cfg)
    d = diagnostics(obs, cfg)
    print("\ndiagnostics")
    for k, v in d.items():
        print(f"  {k:>16s}  {v:.5f}" if isinstance(v, float) else f"  {k:>16s}  {v}")
    print(f"\n  persistence MSE {d['persistence_mse']:.5f} against variance "
          f"{d['variance']:.5f}")
    ratio = d["variance"] / max(d["persistence_mse"], 1e-12)
    print(f"  persistence is {ratio:.1f}x better than predicting the mean")
    if ratio > 50:
        print("  WARNING: the observables barely move between steps. Predicting "
              "'no change' would score very well, so the task may be trivial. "
              "Increase dt, or use a more strongly driven control sequence.")
    elif ratio < 2:
        print("  WARNING: consecutive observations are nearly independent. The "
              "task may be closer to noise than to dynamics. Decrease dt.")
    else:
        print("  Dynamics look well-scaled for a prediction task.")
